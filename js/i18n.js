export const LANGS = { it, en };
let lang = 'it';

export function detectLang(saved) {
  if (saved && LANGS[saved]) return saved;
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'it';
  return /^it\b/i.test(nav) ? 'it' : 'en';
}
export function setLang(l) { lang = LANGS[l] ? l : 'it'; document.documentElement.lang = lang; }
export function getLang() { return lang; }

/** Testo tradotto; {nome} viene sostituito con vars.nome (già sicuro per l'HTML). */
export function t(key, vars = {}) {
  let s = LANGS[lang][key] ?? LANGS.it[key] ?? key;
  if (typeof s !== 'string') return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

export function nCards(n) { return `${n} ${n === 1 ? t('card') : t('cards')}`; }

export function cardLabel(c) {
  return t('cardName', { rank: t('rank')[c.r], suit: t('suit.' + c.s) });
}

/** Applica le traduzioni ai testi fissi della pagina (attributi data-i18n). */
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
